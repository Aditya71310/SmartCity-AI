function buildHourlyTrend(baseAqi: number, basePm25: number) {
  const labels = [
    '00:00', '02:00', '04:00', '06:00', '08:00', '10:00',
    '12:00', '14:00', '16:00', '18:00', '20:00', '22:00',
  ];
  return labels.map((hour, idx) => {
    const wave = Math.sin((idx / 11) * Math.PI * 1.8) * 14 + (idx >= 4 && idx <= 9 ? 11 : -5);
    const aqi = Math.max(28, Math.round(baseAqi + wave));
    const pm25 = Math.max(12, Math.round(basePm25 + wave * 0.65));
    const noiseDb = Math.round(56 + (idx >= 4 && idx <= 10 ? 18 : 4) + (idx % 3) * 3);
    return { hour, aqi, pm25, noiseDb };
  });
}

