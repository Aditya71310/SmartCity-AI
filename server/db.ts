let cachedDb: SmartCityDatabase | null = null;

export function getDb(): SmartCityDatabase {
  if (cachedDb) return cachedDb;
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(DB_FILE)) {
    const seeded = createSeedDatabase();
    fs.writeFileSync(DB_FILE, JSON.stringify(seeded, null, 2), 'utf8');
    cachedDb = seeded;
    return cachedDb;
  }
  try {
    const raw = fs.readFileSync(DB_FILE, 'utf8');
    cachedDb = JSON.parse(raw) as SmartCityDatabase;
    return cachedDb;
  } catch {
    const seeded = createSeedDatabase();
    fs.writeFileSync(DB_FILE, JSON.stringify(seeded, null, 2), 'utf8');
    cachedDb = seeded;
    return cachedDb;
  }
}

export function saveDb(db: SmartCityDatabase): void {
  cachedDb = db;
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  const tmpFile = `${DB_FILE}.tmp`;
  fs.writeFileSync(tmpFile, JSON.stringify(db, null, 2), 'utf8');
  fs.renameSync(tmpFile, DB_FILE);
}

export function resetDbToSeed(): SmartCityDatabase {
  const seeded = createSeedDatabase();
  saveDb(seeded);
  return seeded;
}
